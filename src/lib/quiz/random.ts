/**
 * Tiny deterministic RNG helpers.
 *
 * The daily quiz must be the same for everyone on a given date, so it's built
 * from a seed derived from that date. Practice mode passes `Math.random`
 * instead for fresh questions every time. Everything downstream (shuffles,
 * distractor picks) takes an `Rng` — a function returning a float in [0, 1).
 */

export type Rng = () => number;

/** FNV-1a string hash → 32-bit unsigned int, used to seed the daily RNG. */
export function hashString(input: string): number {
  let h = 2166136261;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** mulberry32 — small, fast, well-distributed seeded PRNG. */
export function mulberry32(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Fisher–Yates shuffle into a new array using the supplied RNG. */
export function shuffle<T>(items: readonly T[], rng: Rng): T[] {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
